const STORAGE_KEY = 'unicode-frames-language';

function initialLanguage() {
  const param = new URLSearchParams(location.search).get('lang');
  if (param in STRINGS) return param;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved in STRINGS) return saved;
  } catch { /* storage unavailable */ }
  return 'en';
}

let language = initialLanguage();

export function getLanguage() {
  return language;
}

export function t(key, vars = {}) {
  const template = STRINGS[language][key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

export function formatNumber(n) {
  return n.toLocaleString(language === 'ja' ? 'ja-JP' : 'en-US');
}

// data-i18n: text; data-i18n-html: trusted markup; data-i18n-label: aria-label; data-i18n-placeholder.
export function applyLanguage(next = language) {
  language = next;
  try { localStorage.setItem(STORAGE_KEY, language); } catch { /* storage unavailable */ }
  document.documentElement.lang = language;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of document.querySelectorAll('[data-i18n-label]')) el.setAttribute('aria-label', t(el.dataset.i18nLabel));
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
}
